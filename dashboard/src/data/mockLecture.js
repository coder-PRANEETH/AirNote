export function formatTime(seconds) {
  const m = Math.floor(seconds / 60);
  const s = seconds % 60;
  return `${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}`;
}

export function getBoardById(id) {
  return BOARD_CAPTURES.find((b) => b.id === id);
}

export function getSpeechAtTime(time) {
  const segments = [...SPEECH_SEGMENTS].filter((s) => s.timestamp <= time);
  return segments[segments.length - 1] ?? SPEECH_SEGMENTS[0];
}

export function getBoardAtTime(time) {
  const boards = [...BOARD_CAPTURES].filter((b) => b.timestamp <= time);
  return boards[boards.length - 1] ?? BOARD_CAPTURES[0];
}

export function getEventsNearTime(time, windowSec = 30) {
  return TIMELINE_EVENTS.filter(
    (e) => Math.abs(e.timestamp - time) <= windowSec,
  );
}
